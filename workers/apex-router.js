/**
 * Apex domain router for signedreviews.com.
 *
 * Uses a service binding (env.LANDING) to talk to the landing Worker —
 * bypasses the public *.workers.dev URL where same-account cross-Worker
 * fetches return 404 for valid paths.
 *
 * Strategy: try the landing Pages project first. If it answers 404, that path
 * doesn't exist, so the landing's own 404 response (status + body) is returned
 * as-is — a real 404 instead of the platform SPA's 200 shell. Platform-owned
 * multi-segment routes are the exception: they fall through to the platform SPA
 * on Railway, which is where they are actually served from. A landing 5xx (or an
 * unreachable landing) also falls through, for resilience.
 *
 * Markdown for Agents: when Accept: text/markdown is present, serve the page's
 * markdown twin (<page>/index.md, generated by build.js from the built HTML).
 */

const PLATFORM_ORIGIN = 'https://platform.signedreviews.com';
const LANDING_ORIGIN = 'https://signedreviews-landing.pages.dev';
// The Express backend. Note the double /api: the app mounts its routers under
// /api, and this host does not strip the prefix. platform.signedreviews.com
// serves the SPA shell for /api/* paths, so it cannot answer an API question.
const API_ORIGIN = 'https://api.signedreviews.com';

// ── Known landing-page path prefixes ─────────────────────────────────────
// Single-segment paths that belong to the landing site, not business slugs.
const LANDING_PAGES = new Set([
  '/',
  '/pricing/',
  '/how-it-works/',
  '/blog/',
  '/api/',
  '/about/',
  '/contact/',
  '/privacy/',
  '/terms/',
  '/trust/',
  '/affiliates/',
  '/sitemap/',
  '/subprocessors/',
  '/features/',
  '/demo/',
  '/dpa/',
  '/dmca/',
  '/refund-policy/',
  '/faq/',
  '/docs/',
  '/how-verification-works/',
  '/integrations/',
  '/chrome-extension/',
]);

// Prefixes that are always landing content (not business profiles).
const LANDING_PREFIXES = [
  '/blog/',
  '/learn/',
  '/vs/',
  '/integrations/',
  '/legal/',
];

function isLandingPath(pathname) {
  if (LANDING_PAGES.has(pathname)) return true;
  // Normalize to trailing slash for comparison.
  const p = pathname.endsWith('/') ? pathname : pathname + '/';
  if (LANDING_PAGES.has(p)) return true;
  return LANDING_PREFIXES.some(pref => p.startsWith(pref));
}

// Business-profile sub-paths: /:slug/leave-a-review and /:slug/reviews.
// These are platform routes, not landing pages — the landing has no such
// pages, so asking it first would waste a request and return its 404.
const BP_SUB_RE = /^\/[^/]+\/(leave-a-review|reviews)(\/.*)?$/;

// ── Markdown for Agents ─────────────────────────────────────────────────────
// Every indexable landing page has a markdown twin at <page>/index.md, written
// by build.js (scripts/markdown-twins.js) from the same build as the HTML, so an
// agent always gets the current copy. This replaced hand-written markdown that
// drifted from the pages. Paths with no twin (platform routes, hidden pages) get
// the short overview below. Keep this block in step with functions/[[path]].js.

const SITE_OVERVIEW = `# Signed Reviews: site overview

Signed Reviews collects customer reviews for businesses paid through Stripe. Review links go only to customers with a completed Stripe charge, each review is matched to that charge, and each review is signed so later edits can be detected. Anyone can check a review on its public verification page.

## Main pages
- [How it works](https://signedreviews.com/how-it-works/)
- [How review verification works](https://signedreviews.com/how-verification-works/)
- [Pricing](https://signedreviews.com/pricing/): free plan, paid plans from $29/mo
- [Fake review checker](https://signedreviews.com/tools/fake-review-checker/): free tool
- [Public API](https://signedreviews.com/api/)
- [Blog](https://signedreviews.com/blog/)

## For AI agents
- [llms.txt](https://signedreviews.com/llms.txt): site map for language models
- [Sitemap](https://signedreviews.com/sitemap.xml): every page on this site
- Any page as markdown: send \`Accept: text/markdown\`, or add \`index.md\` to a page URL that ends in \`/\`.
`;

function defaultMarkdown(pathname) {
  return `> \`${pathname}\` has no markdown version. Site overview follows.\n\n${SITE_OVERVIEW}`;
}

// 404 body: the overview plus an explicit note that the requested path is not
// on this site, so an agent can recover from the sitemap.
function missingMarkdown(pathname) {
  return `> **404:** \`${pathname}\` does not exist on this site. The sitemap lists every page that does.\n\n${SITE_OVERVIEW}`;
}

// Rough heuristic: ~4 chars/token for English. Used for x-markdown-tokens.
function estimateTokens(markdown) {
  return Math.ceil(markdown.length / 4);
}

// The twin's URL for a page path, or null for a file path (/llms.txt,
// /auth.md...), which is served as itself.
function twinPath(pathname) {
  if (/\.[a-z0-9]+$/i.test(pathname)) return null;
  return (pathname.endsWith('/') ? pathname : pathname + '/') + 'index.md';
}

function markdownResponse(markdown, status, source) {
  return new Response(markdown, {
    status,
    headers: {
      'Content-Type': 'text/markdown; charset=utf-8',
      'x-markdown-tokens': String(estimateTokens(markdown)),
      'x-markdown-source': source,
      'x-debug-source': 'apex-router-worker',
      'Cache-Control': 'public, max-age=3600',
      'Vary': 'Accept',
    },
  });
}

async function fetchTwin(pathname) {
  try {
    const res = await fetch(LANDING_ORIGIN + twinPath(pathname), { method: 'GET', redirect: 'manual' });
    if (res.status !== 200) return null;
    const text = await res.text();
    return text.startsWith('---') ? text : null; // guard against an HTML fallback page
  } catch (_) {
    return null;
  }
}

// Answer a markdown request, or return null to let normal routing serve it.
async function serveMarkdown(pathname) {
  if (!twinPath(pathname)) return null;
  const twin = await fetchTwin(pathname);
  if (twin) return markdownResponse(twin, 200, 'twin');
  const status = await markdownStatusFor(pathname);
  return status === 404
    ? markdownResponse(missingMarkdown(pathname), 404, 'missing')
    : markdownResponse(defaultMarkdown(pathname), 200, 'overview');
}

// ── Existence check for the markdown surface ──────────────────────────────
// The markdown branch answers for any path, so it used to report 200 for paths
// that don't exist. Ask the landing origin for the same pathname the way the
// HTML path does below. Only landing-shaped paths are checked — platform routes
// (and the /ph/* proxy, which a more specific route sends to another Worker)
// keep today's behaviour. An explicit landing 404 becomes a 404; anything else
// (a redirect for a non-slash URL, 2xx, 5xx, an unreachable landing) stays 200,
// because we never report a page missing when we cannot prove it is.
async function markdownStatusFor(pathname) {
  if (!isLandingPath(pathname)) return 200;
  try {
    // No headers are forwarded: the landing's own markdown negotiation keys off
    // Accept, and we want its plain static-asset / 404 answer here.
    const landingResponse = await fetch(LANDING_ORIGIN + pathname, {
      method: 'GET',
      redirect: 'manual',
    });
    return landingResponse.status === 404 ? 404 : 200;
  } catch (_) {
    return 200;
  }
}

// ── Main handler ───────────────────────────────────────────────────────────

// Helper: proxy this request to the platform SPA origin.
function proxyToPlatform(request, url) {
  const target = PLATFORM_ORIGIN + url.pathname + url.search;
  const init = {
    method: request.method,
    redirect: 'manual',
  };
  if (request.method !== 'GET' && request.method !== 'HEAD') {
    init.body = request.body;
  }
  return fetch(target, init);
}

// ── Business-profile slug existence ────────────────────────────────────────
// Single-segment paths are assumed to be business profiles (/:slug). The SPA
// answers 200 for every path — its nginx try_files falls back to index.html —
// so a slug with no page behind it renders as a soft 404. Ask the public page
// API instead, which answers 404 when no reachable page has that slug.
//
// Existence is NOT enforced when testmode=1 is set. That is the merchant
// preview flag, and an unpublished page answers 404 to an anonymous lookup by
// design — enforcing here would 404 the merchant's own preview of a page they
// have not published yet (ReviewPageSettings builds /:slug?testmode=1 for
// exactly that case).
const SLUG_CHECK_ORIGIN = 'https://slug-check.signedreviews.internal/';

// Single-segment paths the platform SPA owns. None of these can be a business
// slug — the backend reserves them (RESERVED_SLUGS in routes/reviewPage.js) —
// so they must proxy without a lookup. Mirrors that list, plus /install (an SPA
// route the backend does not reserve); keep the two in step.
const PLATFORM_SINGLE_SEGMENT = new Set([
  'www', 'api', 'app', 'admin', 'dashboard', 'widget', 'verify', 'business',
  'static', 'assets', 'b', 'login', 'logout', 'register', 'callback',
  'confirm-age', 'review', 'invite', 'onboarding', 'onboard', 'me', 'account',
  'settings', 'webhooks', 'oauth', 'support', 'pages', 'page', 'public',
  'install',
]);

async function profileExists(slug) {
  const cacheKey = new Request(SLUG_CHECK_ORIGIN + encodeURIComponent(slug));
  try {
    const hit = await caches.default.match(cacheKey);
    if (hit) return (await hit.text()) === '1';
  } catch (_) {
    // cache unavailable — fall through to a live lookup
  }

  let exists;
  try {
    // HEAD: same route and same 404 semantics as the SPA's GET, without
    // transferring the page payload (~47 KB). Any status other than 404 — a
    // 429 from the public limiter, a 5xx, a network failure — counts as
    // existing, so we never 404 a page we cannot prove is absent.
    const res = await fetch(
      `${API_ORIGIN}/api/review-page/page/${encodeURIComponent(slug)}`,
      { method: 'HEAD', redirect: 'manual' },
    );
    exists = res.status !== 404;
  } catch (_) {
    return true;
  }

  try {
    // Positives hold longer. A negative is short-lived so a page published
    // moments ago is not 404'd for long.
    await caches.default.put(cacheKey, new Response(exists ? '1' : '0', {
      headers: { 'Cache-Control': `public, max-age=${exists ? 300 : 60}` },
    }));
  } catch (_) {
    // caching is best-effort
  }
  return exists;
}

// Unknown paths get the landing's own 404 page — same status and body the
// landing-first block below hands back for an unknown multi-segment path.
async function pageNotFound(request, url) {
  try {
    const res = await fetch(LANDING_ORIGIN + url.pathname, {
      method: request.method,
      redirect: 'manual',
    });
    if (res.status === 404) return res;
  } catch (_) {
    // landing unreachable — fall back to a bare 404 below
  }
  return new Response('Not found', {
    status: 404,
    headers: {
      'Content-Type': 'text/plain; charset=utf-8',
      'X-Robots-Tag': 'noindex',
    },
  });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const accept = request.headers.get('Accept') || '';

    // Markdown for Agents: serve the page's built markdown twin (see
    // serveMarkdown). File paths fall through and are served as themselves.
    if (accept.includes('text/markdown')) {
      const md = await serveMarkdown(url.pathname);
      if (md) return md;
    }

    // Business-profile sub-paths (/:slug/leave-a-review, /:slug/reviews)
    // are platform routes, not landing pages — the landing has no such
    // pages, so asking it first would waste a request and return its 404.
    if (BP_SUB_RE.test(url.pathname)) {
      return proxyToPlatform(request, url);
    }

    // ── Platform assets (must bypass the landing) ──────────────────────────────
    // The landing Pages project has no such files and answers 404 (its HTML 404
    // page) for them — serving that HTML in place of a JS/CSS bundle or an image
    // breaks the platform SPA. Route platform-owned paths directly.

    // Vite build output — the SPA's hashed JS/CSS bundles live under /assets/.
    if (url.pathname.startsWith('/assets/')) {
      return proxyToPlatform(request, url);
    }

    // Root-level images referenced by the platform SPA (logo marks).
    const PLATFORM_ROOT_ASSETS = [
      '/SignedReviews_logo_only.png',
      '/SignedReviews_font_only.png',
    ];
    if (PLATFORM_ROOT_ASSETS.includes(url.pathname)) {
      return proxyToPlatform(request, url);
    }

    // Platform SPA routes that are reachable on the apex and are multi-segment.
    // They must keep falling through to the platform even when the landing
    // answers 404 for them (the landing has no such pages). See
    // platform/frontend/src/App.jsx: /review/preview/:businessId, /review/:token,
    // /verify/:reviewId, /invite/:token, /business/:slug, /b/:slug, and the
    // /dashboard/* children. /:slug/reviews and /:slug/leave-a-review are already
    // handled earlier by BP_SUB_RE and must not be duplicated here.
    const PLATFORM_ROUTE_PREFIXES = [
      '/review/',
      '/verify/',
      '/invite/',
      '/business/',
      '/b/',
      '/dashboard/',
    ];

    // Single-segment paths that aren't known landing pages are business
    // profiles (/:slug). Route them to the platform SPA. Static assets at
    // root level (.css, .js, images, etc.) may belong to either project;
    // the platform-specific ones are handled above — the rest fall through
    // to the landing-first logic below.
    const SINGLE_SEGMENT_RE = /^\/[^/]+\/?$/;
    const STATIC_ASSET_RE = /\.(css|js|md|png|jpe?g|gif|svg|ico|webp|woff2?|ttf|xml|txt|json|webmanifest|pdf|map)$/i;
    if (SINGLE_SEGMENT_RE.test(url.pathname) && !isLandingPath(url.pathname) && !STATIC_ASSET_RE.test(url.pathname)) {
      // A profile URL must resolve to a real page. Unmatched single-segment
      // paths otherwise reach the SPA and get its 200 shell — a soft 404.
      const isReadable = request.method === 'GET' || request.method === 'HEAD';
      if (isReadable && url.searchParams.get('testmode') !== '1') {
        const slug = url.pathname.replace(/^\/+|\/+$/g, '');
        if (!PLATFORM_SINGLE_SEGMENT.has(slug) && !(await profileExists(slug))) {
          return pageNotFound(request, url);
        }
      }
      return proxyToPlatform(request, url);
    }

    // Everything else: try the landing Pages project first.
    // Use the public pages.dev URL — service bindings to Pages projects
    // sometimes don't serve static assets correctly.
    //
    // NOTE: the landing Pages project serves real pages, and answers 404 with
    // its own 404.html for anything it doesn't have (including /assets/* and
    // random slugs). The guards above ensure platform-owned paths never reach
    // this block. If you add a new platform asset prefix, add it above — not here.
    try {
      const target = LANDING_ORIGIN + url.pathname + url.search;
      const landingResponse = await fetch(target, {
        method: request.method,
        headers: request.headers,
        redirect: 'manual',
      });
      if (landingResponse.status !== 404 && landingResponse.status < 500) {
        // Markdown twins requested directly: point search engines at the HTML page.
        if (url.pathname.endsWith('/index.md') && landingResponse.status === 200) {
          const headers = new Headers(landingResponse.headers);
          headers.set('Content-Type', 'text/markdown; charset=utf-8');
          headers.set('X-Robots-Tag', 'noindex');
          headers.set('Link', `<https://signedreviews.com${url.pathname.slice(0, -'index.md'.length)}>; rel="canonical"`);
          return new Response(landingResponse.body, { status: 200, headers });
        }
        return landingResponse;
      }
      // Landing 404 → the path genuinely doesn't exist. Return the landing's 404
      // response as-is (it already carries the 404 status and the correct body)
      // so crawlers see a hard 404 instead of the platform SPA's 200 shell, which
      // Google treats as a soft 404. Platform-owned routes are the exception:
      // they don't exist in the landing project either, so keep the fallthrough.
      if (landingResponse.status === 404 && !PLATFORM_ROUTE_PREFIXES.some(pref => url.pathname.startsWith(pref))) {
        return landingResponse;
      }
    } catch (_) {
      // landing unreachable — fall through to platform
    }

    // Platform-owned route, landing 5xx, or landing unreachable → platform SPA.
    return proxyToPlatform(request, url);
  },
};
